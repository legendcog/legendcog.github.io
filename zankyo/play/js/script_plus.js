const PLUS_MISS = [];
function plusIns(scene, head, lines, before) {
  const i = scene.findIndex((x) => typeof x === "string" && x.startsWith(head));
  if (i < 0) { PLUS_MISS.push(head); if (typeof console !== "undefined") console.error("台本の差しこみ先が無い:", head); return; }
  scene.splice(i + (before ? 0 : 1), 0, ...lines);
}
