/* 再現の図：その人の「最後に分かること」（act2・ending）の手前に、区間を足す */
function rcIns(who, ...segs) {
  const a = RC_SEG[who]; let i = a.findIndex((s) => /act2|ending/.test(s[3])); if (i < 0) i = a.length;
  a.splice(i, 0, ...segs);
}
/* 再現の図：出来事を、時刻の順に足す */
function rcEvent(ev) {
  const t = (s) => +s.slice(0, 2) * 60 + +s.slice(3);
  let i = RC_EVENTS.findIndex((e) => t(e[0]) > t(ev[0])); if (i < 0) i = RC_EVENTS.length;
  RC_EVENTS.splice(i, 0, ev);
}
/* 最後の推理の「つきつける」に、正解を足す */
function plusOk(scene, part, ids, note) {
  const p = scene.find((x) => x && x.present && x.present.q.indexOf(part) >= 0);
  if (p) p.present.ok.push(...ids); else PLUS_MISS.push(note || part);
}

